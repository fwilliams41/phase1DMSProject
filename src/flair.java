public class flair {
    public static final String RESET = "\u001B[0m";

    // Regular Colors
    public static final String RED = "\u001B[31m";
    public static final String GREEN = "\u001B[32m";
    public static final String YELLOW = "\u001B[33m";
    public static final String BLUE = "\u001B[34m";
    public static final String PURPLE = "\u001B[35m";
    public static final String CYAN = "\u001B[36m";
    public static final String WHITE = "\u001B[37m";

    // Custom Accent Tones
    public static final String PINK = "\u001B[38;5;205m";     // Vibrant Neon Pink
    public static final String ORANGE = "\u001B[38;5;208m";   // Bright Bookish Orange

    // Bold Styles (Great for headers and totals)
    public static final String BOLD_CYAN = "\u001B[1;36m";
    public static final String BOLD_PINK = "\u001B[1;38;5;205m";
    public static final String BOLD_GREEN = "\u001B[1;32m";
    public static final String BOLD_RED = "\u001B[1;31m";
}

